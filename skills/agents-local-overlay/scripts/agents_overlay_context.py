def ensure_bridge(
    path: Path, marker: str, changes: List[str], problems: List[str]
) -> None:
    try:
        state = bridge_state(path, marker)
    except OverlayError as exc:
        problems.append(str(exc))
        return
    if not state.exists:
        try:
            atomic_write(path, marker + "\n")
        except OverlayError as exc:
            problems.append(str(exc))
            return
        changes.append(f"{path}: created {marker} bridge")
        return
    if state.exact:
        return
    if state.normalizable:
        try:
            atomic_write(path, marker + "\n")
        except OverlayError as exc:
            problems.append(str(exc))
            return
        changes.append(f"{path}: normalized to {marker} bridge")
        return
    problems.append(
        f"{path} contains content beyond the {marker} import; move that content "
        f"to the rule source file and leave the one-line bridge"
    )


def setup_command(argv: Sequence[str]) -> int:
    project_dir = argv[0] if argv else "."
    ctx = resolve_context(project_dir, require_git=True)
    changes: List[str] = []
    problems: List[str] = []
    ctx = drop_missing_worktrees(ctx, problems)
    problems.extend(worktree_nesting_problems(ctx))

    shared_exists = path_exists(shared_source_path(ctx))
    local_exists = path_exists(local_source_path(ctx))
    if not shared_exists and not local_exists:
        fail(
            f"agents-overlay-context: create {SHARED_RULE} and/or {LOCAL_RULE} "
            "first, then run setup"
        )

    local_text: Optional[str] = None
    if local_exists:
        try:
            local_text = read_rule(local_source_path(ctx))
        except OverlayError as exc:
            problems.append(str(exc))
    if shared_exists:
        try:
            read_rule(shared_source_path(ctx))
        except OverlayError as exc:
            problems.append(str(exc))
        ensure_bridge(ctx.top / CLAUDE_SHARED_BRIDGE, SHARED_BRIDGE_MARKER, changes, problems)

    if local_text is not None:
        if not ctx.root_is_bare:
            ensure_bridge(ctx.root / CLAUDE_LOCAL_BRIDGE, LOCAL_BRIDGE_MARKER, changes, problems)
    if local_text is not None or not local_exists:
        for worktree in ctx.copy_worktrees:
            copy_notices: List[str] = []
            if refresh_generated_copy(worktree, local_text, copy_notices):
                verb = "refreshed" if local_text is not None else "removed orphan"
                changes.append(f"{worktree / CLAUDE_LOCAL_BRIDGE}: {verb} generated copy")
            problems.extend(copy_notices)

    ensure_ignores(ctx, changes, problems)

    for line in changes:
        print(f"changed: {line}")
    for line in problems:
        print(f"problem: {line}", file=sys.stderr)
    if problems:
        return 1
    print("setup: running verify")
    return verify_command([str(ctx.start)])


