# --- process helpers ---------------------------------------------------------


def run_git(
    cwd: Path, args: Sequence[str], check: bool = True
) -> subprocess.CompletedProcess[bytes]:
    if not cwd.is_dir():
        raise OverlayError(f"cannot run git in {cwd}: directory does not exist")
    try:
        proc = subprocess.run(
            ["git", *args],
            cwd=str(cwd),
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            check=False,
        )
    except FileNotFoundError:
        raise OverlayError("git is required")
    if check and proc.returncode != 0:
        detail = proc.stderr.decode("utf-8", "replace").strip()
        suffix = f": {detail}" if detail else ""
        raise OverlayError(f"git {' '.join(args)} failed{suffix}")
    return proc


def one_line_stdout(proc: subprocess.CompletedProcess[bytes], label: str) -> Path:
    data = proc.stdout
    if not data.endswith(b"\n"):
        raise OverlayError(f"{label} did not return one newline-terminated path")
    try:
        return Path(data[:-1].decode("utf-8"))
    except UnicodeDecodeError as exc:
        raise OverlayError(f"{label} returned a non-UTF-8 path") from exc


# --- repo context ------------------------------------------------------------


@dataclass(frozen=True)
class RepoContext:
    start: Path
    top: Path
    root: Path
    common: Path
    worktrees: Tuple[Path, ...]

    @property
    def root_is_bare(self) -> bool:
        try:
            if self.root == self.common or os.path.samefile(self.root, self.common):
                return True
        except OSError:
            pass
        return False

    @property
    def checkout_worktrees(self) -> Tuple[Path, ...]:
        if self.root_is_bare:
            return tuple(w for w in self.worktrees if w != self.root)
        return self.worktrees

    @property
    def copy_worktrees(self) -> Tuple[Path, ...]:
        """Worktrees whose CLAUDE.local.md is a generated content copy."""
        return tuple(w for w in self.checkout_worktrees if w != self.root)


def resolve_context(project_dir: str, require_git: bool = False) -> RepoContext:
    try:
        start = Path(project_dir).resolve(strict=True)
    except (OSError, RuntimeError) as exc:
        raise OverlayError(f"cannot enter project directory: {project_dir}") from exc
    if not start.is_dir():
        raise OverlayError(f"project directory is not a directory: {project_dir}")
    top_proc = run_git(
        start, ["rev-parse", "--path-format=absolute", "--show-toplevel"], check=False
    )
    if top_proc.returncode != 0:
        if require_git:
            raise OverlayError("run inside a Git worktree")
        raise QuietExit()
    top = one_line_stdout(top_proc, "git rev-parse --show-toplevel")
    common = one_line_stdout(
        run_git(top, ["rev-parse", "--path-format=absolute", "--git-common-dir"]),
        "git rev-parse --git-common-dir",
    )
    records = run_git(top, ["worktree", "list", "--porcelain", "-z"]).stdout.split(b"\0")
    if not records or not records[0].startswith(b"worktree "):
        raise OverlayError("could not resolve primary worktree")
    worktrees: List[Path] = []
    for record in records:
        if not record.startswith(b"worktree "):
            continue
        try:
            worktrees.append(Path(record[len(b"worktree ") :].decode("utf-8")))
        except UnicodeDecodeError as exc:
            raise OverlayError("worktree path is not UTF-8") from exc
    root = worktrees[0]
    if not root.is_absolute():
        raise OverlayError("primary worktree path is not absolute")
    if not root.is_dir():
        raise OverlayError("primary worktree path is not a directory")
    # /tmp vs /private/tmp style aliases break membership/equality checks, so
    # every context path is stored fully resolved.
    return RepoContext(
        start=resolved_or_self(start),
        top=resolved_or_self(top),
        root=resolved_or_self(root),
        common=resolved_or_self(common),
        worktrees=tuple(resolved_or_self(w) for w in worktrees),
    )


def path_exists(path: Path) -> bool:
    return os.path.lexists(path)


def resolved_or_self(path: Path) -> Path:
    try:
        return path.resolve(strict=False)
    except (OSError, RuntimeError):
        return path


def path_is_within(path: Path, ancestor: Path) -> bool:
    try:
        resolved_or_self(path).relative_to(resolved_or_self(ancestor))
    except ValueError:
        return False
    return True


def worktrees_nest(a: Path, b: Path) -> bool:
    return a != b and (path_is_within(a, b) or path_is_within(b, a))


def worktree_nesting_problems(ctx: RepoContext) -> List[str]:
    problems: List[str] = []
    seen = ctx.worktrees
    for i, outer in enumerate(seen):
        for inner in seen[i + 1 :]:
            if worktrees_nest(outer, inner):
                problems.append(
                    f"worktrees must not nest: {outer} and {inner}; "
                    "move one outside the other"
                )
    return problems


def drop_missing_worktrees(ctx: RepoContext, problems: List[str]) -> RepoContext:
    """Report registered worktrees whose directory is gone and exclude them.

    The primary is always present because resolve_context requires it.
    """
    present = []
    for worktree in ctx.worktrees:
        if worktree.is_dir():
            present.append(worktree)
            continue
        problems.append(
            f"{worktree} is registered as a worktree but does not exist; run "
            "git worktree prune (deleted) or git worktree repair (moved)"
        )
    if len(present) == len(ctx.worktrees):
        return ctx
    return replace(ctx, worktrees=tuple(present))


def worktree_topology_notices(ctx: RepoContext) -> List[str]:
    """Delivery problems caused by where this checkout sits, not by its files."""
    notices: List[str] = []
    if ctx.top not in ctx.worktrees:
        notices.append(
            f"Rules not delivered: {ctx.top} is not in git worktree list (moved "
            f"without git worktree move?); its {CLAUDE_LOCAL_BRIDGE} copy is not "
            "refreshed — run git worktree repair, then agents-overlay-context setup"
        )
    for other in ctx.worktrees:
        if worktrees_nest(ctx.top, other):
            notices.append(
                f"Rules may be duplicated: {ctx.top} nests with worktree {other}; "
                "Claude loads rule files from both directories — move one outside "
                "the other"
            )
    return notices


# --- rule file IO ------------------------------------------------------------


def rule_refusal_detail(path: Path) -> str:
    try:
        mode = path.lstat().st_mode
    except OSError as exc:
        return f"could not inspect rule file {path}: {exc}"
    if stat.S_ISLNK(mode):
        return f"{path} is a symlink; symlinked rule files are never read as rules"
    if not stat.S_ISREG(mode):
        return f"{path} is not a regular file"
    if not os.access(path, os.R_OK):
        return f"{path} is not readable"
    return f"{path} is not a readable regular file"


def read_regular_file_bytes(path: Path) -> bytes:
    nofollow = getattr(os, "O_NOFOLLOW", 0)
    if nofollow == 0:
        try:
            mode = path.lstat().st_mode
        except OSError as exc:
            raise OverlayError(f"could not inspect rule file {path}: {exc}") from exc
        if stat.S_ISLNK(mode):
            raise OverlayError(rule_refusal_detail(path))
    try:
        fd = os.open(path, os.O_RDONLY | nofollow)
    except OSError as exc:
        raise OverlayError(rule_refusal_detail(path)) from exc
    try:
        st = os.fstat(fd)
        if not stat.S_ISREG(st.st_mode):
            raise OverlayError(f"{path} is not a regular file")
        chunks = []
        while True:
            chunk = os.read(fd, 65536)
            if not chunk:
                break
            chunks.append(chunk)
        return b"".join(chunks)
    finally:
        os.close(fd)


def decode_rule(data: bytes, desc: str) -> str:
    try:
        text = data.decode("utf-8")
    except UnicodeDecodeError as exc:
        raise OverlayError(f"rule file is not UTF-8: {desc}") from exc
    if "\0" in text:
        raise OverlayError(f"rule file contains NUL: {desc}")
    return text.rstrip("\n")


def read_rule(path: Path) -> str:
    return decode_rule(read_regular_file_bytes(path), str(path))


def atomic_write(path: Path, data: str) -> None:
    file_mode = 0o644
    if path_exists(path):
        try:
            mode = path.lstat().st_mode
        except OSError as exc:
            raise OverlayError(f"could not inspect {path}: {exc}") from exc
        if stat.S_ISLNK(mode) or not stat.S_ISREG(mode):
            raise OverlayError(f"{path} is not a regular file")
        file_mode = stat.S_IMODE(mode) & 0o777
    tmp_path: Optional[Path] = None
    try:
        with tempfile.NamedTemporaryFile(
            mode="w",
            encoding="utf-8",
            newline="\n",
            dir=path.parent,
            prefix=f".{path.name}.",
            delete=False,
        ) as tmp:
            tmp_path = Path(tmp.name)
            tmp.write(data)
        tmp_path.chmod(file_mode)
        os.replace(tmp_path, path)
        tmp_path = None
    except OSError as exc:
        raise OverlayError(f"could not write {path}: {exc}") from exc
    finally:
        if tmp_path is not None:
            try:
                tmp_path.unlink()
            except OSError:
                pass


# --- bridges and generated copies -------------------------------------------


def bridge_is_exact(data: bytes, marker: str) -> bool:
    expected = marker.encode("utf-8")
    return data == expected or data == expected + b"\n"


def bridge_is_normalizable(data: bytes, marker: str) -> bool:
    if bridge_is_exact(data, marker):
        return True
    try:
        text = data.decode("utf-8")
    except UnicodeDecodeError:
        return False
    if "\0" in text:
        return False
    if text.startswith("﻿"):
        text = text[1:]
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    content = [line.rstrip() for line in text.split("\n") if line.strip()]
    if len(content) != 1:
        return False
    if content[0] != content[0].lstrip():
        return False
    dotted = "@./" + marker[1:]
    return content[0] in (marker, dotted)


@dataclass(frozen=True)
class BridgeState:
    exists: bool
    exact: bool
    normalizable: bool


def bridge_state(path: Path, marker: str) -> BridgeState:
    if not path_exists(path):
        return BridgeState(exists=False, exact=False, normalizable=False)
    data = read_regular_file_bytes(path)
    exact = bridge_is_exact(data, marker)
    return BridgeState(
        exists=True,
        exact=exact,
        normalizable=exact or bridge_is_normalizable(data, marker),
    )


def generated_copy_text(local_text: str) -> str:
    return GENERATED_LOCAL_OWNER + "\n\n" + local_text + "\n"


@dataclass(frozen=True)
class CopyState:
    exists: bool
    owned: bool
    fresh: bool


def generated_copy_state(path: Path, local_text: Optional[str]) -> CopyState:
    if not path_exists(path):
        return CopyState(exists=False, owned=False, fresh=False)
    data = read_regular_file_bytes(path)
    try:
        text = data.decode("utf-8")
    except UnicodeDecodeError:
        return CopyState(exists=True, owned=False, fresh=False)
    owned = text.split("\n", 1)[0] == GENERATED_LOCAL_OWNER
    fresh = owned and local_text is not None and text == generated_copy_text(local_text)
    return CopyState(exists=True, owned=owned, fresh=fresh)


def local_source_path(ctx: RepoContext) -> Path:
    return ctx.root / LOCAL_RULE


def shared_source_path(ctx: RepoContext) -> Path:
    return ctx.top / SHARED_RULE


def overlay_opted_in(ctx: RepoContext) -> bool:
    if path_exists(local_source_path(ctx)):
        return True
    if ctx.top != ctx.root and path_exists(ctx.top / LOCAL_RULE):
        return True
    for worktree in ctx.copy_worktrees:
        copy = worktree / CLAUDE_LOCAL_BRIDGE
        if path_exists(copy):
            try:
                if generated_copy_state(copy, None).owned:
                    return True
            except OverlayError:
                continue
    if not ctx.root_is_bare:
        bridge = ctx.root / CLAUDE_LOCAL_BRIDGE
        if path_exists(bridge):
            try:
                if bridge_state(bridge, LOCAL_BRIDGE_MARKER).normalizable:
                    return True
            except OverlayError:
                pass
    return False


def refresh_generated_copy(
    worktree: Path, local_text: Optional[str], notices: List[str]
) -> bool:
    """Bring one worktree's generated CLAUDE.local.md in line with the source.

    Returns True when the file was created, rewritten, or removed.
    """
    target = worktree / CLAUDE_LOCAL_BRIDGE
    try:
        state = generated_copy_state(target, local_text)
    except OverlayError as exc:
        notices.append(f"Rules not delivered: {exc}")
        return False
    if local_text is None:
        if state.exists and state.owned:
            try:
                os.remove(target)
            except OSError as exc:
                notices.append(f"Rules not delivered: could not remove stale {target}: {exc}")
                return False
            return True
        if state.exists and not state.owned:
            notices.append(
                f"Rules not delivered: {target} exists but the primary {LOCAL_RULE} "
                "source is missing; move its content to the primary source"
            )
        return False
    if state.exists and not state.owned:
        notices.append(
            f"Rules not delivered: {target} is not overlay-generated; move its "
            f"content into the primary {LOCAL_RULE} and remove the file"
        )
        return False
    if state.fresh:
        return False
    try:
        atomic_write(target, generated_copy_text(local_text))
    except OverlayError as exc:
        notices.append(f"Rules not delivered: {exc}")
        return False
    return True


# --- rule snapshot -----------------------------------------------------------


def read_optional_rule(path: Path, notices: List[str]) -> Optional[str]:
    if not path_exists(path):
        return None
    try:
        return read_rule(path)
    except OverlayError as exc:
        notices.append(f"Rule file not loaded by overlay: {exc}")
        return None


def labeled_rules(parts: Sequence[Tuple[str, str]]) -> str:
    sections = [f"# {name} (agents-local-overlay)\n\n{text}" for name, text in parts]
    return "\n\n".join(sections)


def over_cap_notice(policy: str, cap: int) -> str:
    return (
        f"Rules not injected: rule text exceeds the {cap}-char {policy} budget; "
        f"shorten {SHARED_RULE}/{LOCAL_RULE} or move rarely needed content to "
        "regular docs opened on demand"
    )


# --- hook emission -----------------------------------------------------------


def notice_lines(notices: Sequence[str]) -> str:
    return "\n".join(NOTICE_PREFIX + notice for notice in notices)


def emit_plain_context(body: str) -> None:
    sys.stdout.write(body + "\n")
    sys.stdout.flush()


def emit_additional_context_json(event: str, body: str) -> None:
    payload = {
        "hookSpecificOutput": {
            "hookEventName": event,
            "additionalContext": body,
        }
    }
    sys.stdout.write(json.dumps(payload) + "\n")
    sys.stdout.flush()


def parse_hook_object(hook_input: str, policy: str) -> dict:
    try:
        hook = json.loads(hook_input)
    except (ValueError, TypeError) as exc:
        raise OverlayError(f"policy {policy} requires JSON hook input") from exc
    if not isinstance(hook, dict):
        raise OverlayError(f"policy {policy} requires object hook input")
    return hook


def hook_cwd(hook: dict, policy: str) -> str:
    cwd = hook.get("cwd")
    if not isinstance(cwd, str) or not cwd:
        raise OverlayError(f"policy {policy} requires hook cwd")
    return cwd


# --- Claude policies ---------------------------------------------------------


def claude_session_notices(ctx: RepoContext) -> List[str]:
    notices: List[str] = []
    if not overlay_opted_in(ctx):
        return notices
    if os.environ.get("CLAUDE_CODE_DISABLE_CLAUDE_MDS") == "1":
        notices.append(
            "Rules not delivered: CLAUDE_CODE_DISABLE_CLAUDE_MDS=1 disables the "
            "native CLAUDE.md channel this overlay relies on; unset it and start "
            "a new session"
        )
    notices.extend(worktree_topology_notices(ctx))
    local_exists = path_exists(local_source_path(ctx))
    local_text = read_optional_rule(local_source_path(ctx), notices)
    notices.extend(missing_shared_notices(ctx))
    notices.extend(stray_local_notices(ctx))
    if path_exists(shared_source_path(ctx)):
        read_optional_rule(shared_source_path(ctx), notices)
        try:
            state = bridge_state(ctx.top / CLAUDE_SHARED_BRIDGE, SHARED_BRIDGE_MARKER)
        except OverlayError as exc:
            state = None
            notices.append(f"Rules not delivered: {exc}")
        if state is not None and not state.exists:
            notices.append(
                f"Rules not delivered: {ctx.top / CLAUDE_SHARED_BRIDGE} bridge is "
                f"missing; run agents-overlay-context setup"
            )
        elif state is not None and not state.normalizable:
            notices.append(
                f"Rules not delivered: {ctx.top / CLAUDE_SHARED_BRIDGE} is not the "
                f"single-line {SHARED_BRIDGE_MARKER} bridge; move extra content to "
                f"{SHARED_RULE} and run agents-overlay-context setup"
            )
    if path_exists(local_source_path(ctx)):
        if not ctx.root_is_bare and ctx.top == ctx.root:
            try:
                state = bridge_state(ctx.root / CLAUDE_LOCAL_BRIDGE, LOCAL_BRIDGE_MARKER)
            except OverlayError as exc:
                state = None
                notices.append(f"Rules not delivered: {exc}")
            if state is not None and not state.exists:
                notices.append(
                    f"Rules not delivered: {ctx.root / CLAUDE_LOCAL_BRIDGE} bridge "
                    "is missing; run agents-overlay-context setup"
                )
            elif state is not None and not state.normalizable:
                notices.append(
                    f"Rules not delivered: {ctx.root / CLAUDE_LOCAL_BRIDGE} is not "
                    f"the single-line {LOCAL_BRIDGE_MARKER} bridge; move extra "
                    f"content to {LOCAL_RULE} and run agents-overlay-context setup"
                )
    # An unreadable source is reported above and keeps the existing copy, the
    # same as setup; only an absent source removes an orphan copy.
    if ctx.top in ctx.copy_worktrees and (local_text is not None or not local_exists):
        refresh_generated_copy(ctx.top, local_text, notices)
    return notices


def claude_session_command(event: str, hook: dict) -> int:
    ctx = resolve_context(hook_cwd(hook, "claude-session"))
    notices = claude_session_notices(ctx)
    if notices:
        emit_plain_context(notice_lines(notices))
    return 0


def claude_subagent_command(event: str, hook: dict) -> int:
    return 0


# --- Codex policies ----------------------------------------------------------


def codex_kiro_precondition_notices(ctx: RepoContext) -> List[str]:
    notices: List[str] = []
    override = ctx.top / CODEX_OVERRIDE
    if path_exists(override):
        notices.append(
            f"Shared rules may be missing: {override} replaces {SHARED_RULE} "
            "for Codex in this worktree; remove it"
        )
    notices.extend(missing_shared_notices(ctx))
    notices.extend(invalid_shared_notices(ctx))
    notices.extend(stray_local_notices(ctx))
    return notices


def missing_shared_notices(ctx: RepoContext) -> List[str]:
    if path_exists(ctx.top / SHARED_RULE):
        return []
    if ctx.top != ctx.root and path_exists(ctx.root / SHARED_RULE):
        return [
            f"Shared rules may be missing: {ctx.top} has no {SHARED_RULE} but the "
            f"primary worktree does; put the shared source in this checkout"
        ]
    return []


def invalid_shared_notices(ctx: RepoContext) -> List[str]:
    shared = ctx.top / SHARED_RULE
    if not path_exists(shared):
        return []
    try:
        read_rule(shared)
    except OverlayError as exc:
        return [f"Shared rules may be missing: {exc}"]
    return []


def stray_local_notices(ctx: RepoContext) -> List[str]:
    if ctx.top == ctx.root:
        return []
    stray = ctx.top / LOCAL_RULE
    if path_exists(stray):
        return [
            f"Rules not delivered: {stray} is not read; the local source lives "
            f"in the primary worktree only — move its content to "
            f"{local_source_path(ctx)}"
        ]
    return []


def codex_hook_command(event: str, hook: dict, policy: str) -> int:
    ctx = resolve_context(hook_cwd(hook, policy))
    if not path_exists(local_source_path(ctx)):
        if stray_local_notices(ctx):
            emit_additional_context_json(event, notice_lines(codex_kiro_precondition_notices(ctx)))
        return 0
    notices = codex_kiro_precondition_notices(ctx)
    local_text = read_optional_rule(local_source_path(ctx), notices)
    body = labeled_rules([(LOCAL_RULE, local_text)]) if local_text is not None else ""
    if body and len(body) > CODEX_MAX_CHARS:
        notices.append(over_cap_notice(policy, CODEX_MAX_CHARS))
        body = ""
    pieces = [piece for piece in (notice_lines(notices), body) if piece]
    if pieces:
        emit_additional_context_json(event, "\n\n".join(pieces))
    return 0


