def hook_command(argv: Sequence[str]) -> int:
    if len(argv) < 5:
        fail("agents-overlay-context: missing arguments\n" + usage())
    event = argv[0]
    policy = argv[4]
    hook_input = sys.stdin.read()
    if policy in ("claude-session", "claude-subagent"):
        hook = parse_hook_object(hook_input, policy)
        if policy == "claude-session":
            return claude_session_command(event, hook)
        return claude_subagent_command(event, hook)
    if policy in ("codex-session", "codex-subagent"):
        hook = parse_hook_object(hook_input, policy)
        return codex_hook_command(event, hook, policy)
    fail(f"agents-overlay-context: unknown policy {policy}\n" + usage())
    return 1


def main(argv: Sequence[str]) -> int:
    if not argv:
        fail("agents-overlay-context: missing command\n" + usage())
    command, rest = argv[0], list(argv[1:])
    try:
        if command == "json":
            return hook_command(rest)
        if command == "kiro-body":
            return kiro_body_command(rest)
        if command == "setup":
            return setup_command(rest)
        if command == "verify":
            return verify_command(rest)
        if command == "claude-worktree-create":
            return claude_worktree_create_command()
        if command == "claude-worktree-remove":
            return claude_worktree_remove_command()
        fail(f"agents-overlay-context: unknown command {command}\n" + usage())
        return 1
    except QuietExit:
        return 0
    except OverlayError as exc:
        fail(f"agents-overlay-context: {exc}")
        return 1


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
